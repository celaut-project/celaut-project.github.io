<div class="block">
	<p class="eyebrow">Common misreadings</p>
	<h2>What Celaut is not</h2>
	<p class="block-intro">
		The architecture sits close enough to several familiar things to be mistaken for them. It is
		worth being precise about the differences.
	</p>

	<div class="rows">
		<div class="row">
			<span class="row-mark" aria-hidden="true">01</span>
			<div>
				<h3>Not a single network</h3>
				<p>
					Celaut defines a <strong>flexible architecture</strong>, not one predetermined network.
					Predominant networks may well emerge, but the system supports many peer-to-peer
					constructions rather than dictating a singular one.
				</p>
			</div>
		</div>

		<div class="row">
			<span class="row-mark" aria-hidden="true">02</span>
			<div>
				<h3>Not a complete protocol stack</h3>
				<p>
					It provides <strong>core principles</strong> for building computation distribution
					stacks, not a full opinionated stack. Current implementations lean on components like
					gRPC or Docker, and those are interchangeable choices.
				</p>
			</div>
		</div>

		<div class="row">
			<span class="row-mark" aria-hidden="true">03</span>
			<div>
				<h3>Not a blockchain project</h3>
				<p>
					Celaut has <strong>no native cryptocurrency</strong> and no DAOs. It does incorporate
					blockchain technologies where they earn their place — recording reputation, settling
					payment between strangers — without adopting the broader ecosystem around them.
				</p>
			</div>
		</div>
	</div>
</div>
